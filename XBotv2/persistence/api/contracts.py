"""Physical SQL, rollout, artifact and lifetime capabilities."""

from __future__ import annotations

from collections.abc import Callable, Sequence
from contextlib import AbstractAsyncContextManager
from typing import Protocol, TypeVar

from pydantic import JsonValue
from xcore.api.services import ServiceKey

from XBotv2.core.api.artifacts import ArtifactStorePort

T = TypeVar("T")


class SqlTransaction(Protocol):
    changed: int

    def execute(
        self, sql: str, parameters: Sequence[object] = ()
    ) -> tuple[tuple[object, ...], ...]: ...


class DomainStore(Protocol):
    async def exists(self) -> bool: ...
    async def transaction(
        self,
        callback: Callable[[SqlTransaction], T],
        *,
        size: int = 0,
        write: bool = True,
    ) -> T: ...


class StatePort(Protocol):
    async def get(self, key: str, default: JsonValue = None) -> JsonValue: ...
    async def set(self, key: str, value: JsonValue) -> None: ...
    async def delete(self, key: str) -> None: ...
    async def clear(self) -> None: ...
    async def keys(self) -> list[str]: ...
    def namespace(self, prefix: str) -> StatePort: ...
    def domain(self, owner: str, tables: Sequence[str]) -> DomainStore: ...


class Ownership(Protocol):
    def release(self) -> None: ...


class RolloutPort(Protocol):
    def bind_projection(self, domain: DomainStore) -> None: ...
    def lease(self, *, write: bool = False) -> AbstractAsyncContextManager[None]: ...
    def reading(self) -> AbstractAsyncContextManager[None]: ...
    async def initialize(self) -> None: ...
    async def reset(self) -> None: ...
    async def recover(self) -> None: ...
    async def append(
        self, kind: str, data: dict, *, identity: str | None = None
    ) -> dict: ...
    async def record(self, identity: str) -> dict: ...
    async def present(self) -> bool: ...
    async def head(self) -> tuple[int, int, int]: ...
    async def flush(self) -> tuple[int, int, int]: ...
    async def records_page(
        self, *, before: int | None = None, limit: int = 128, kinds: Sequence[str] = ()
    ) -> tuple[int, list[tuple[str, int]]]: ...
    async def read_range(
        self,
        *,
        after_seq: int = 0,
        through_seq: int | None = None,
        limit: int = 128,
        max_bytes: int = 1048576,
    ) -> tuple[tuple[dict, ...], int, int]: ...


class PreparedCopy(Protocol):
    session_id: str
    cuts: tuple[tuple[str, int, int], ...]

    async def publish(self) -> None: ...


class Persistence(Protocol):
    record_bytes: int

    def use(
        self, session_id: str | None = None
    ) -> AbstractAsyncContextManager[None]: ...
    def database(
        self, session_id: str, *, owner: str, tables: Sequence[str]
    ) -> DomainStore: ...
    async def database_exists(self, session_id: str) -> bool: ...
    def state(
        self, session_id: str | None = None, thread_id: str = ""
    ) -> StatePort: ...
    def rollout(
        self,
        session_id: str,
        thread_id: str,
        *,
        domain: DomainStore,
        project: Callable[[SqlTransaction, str, Sequence[tuple[dict, int, int]]], None],
    ) -> RolloutPort: ...
    def acquire(self, session_id: str) -> Ownership: ...
    def owns(self, session_id: str) -> bool: ...
    def artifacts(self, session_id: str, thread_id: str) -> ArtifactStorePort: ...
    async def owners(self, session_id: str) -> frozenset[str]: ...
    def copy_session(
        self, source_id: str, target_id: str
    ) -> AbstractAsyncContextManager[PreparedCopy]: ...
    def prepare_session(
        self, target_id: str
    ) -> AbstractAsyncContextManager[PreparedCopy]: ...
    async def copy_document(
        self, source_id: str, target_id: str, name: str
    ) -> None: ...
    async def drain(self, session_id: str | None = None) -> None: ...
    async def delete_session(self, session_id: str) -> None: ...


PERSISTENCE: ServiceKey[Persistence] = ServiceKey("persistence")
