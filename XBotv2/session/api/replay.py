"""Process-owned shared event replay capacity."""

from typing import Any, Protocol
import asyncio
from xcore.api.services import ServiceKey


class ReplayWindowPort(Protocol):
    @property
    def oldest(self) -> Any | None: ...
    def append(self, frame: Any, size: int) -> None: ...
    def get(self, index: int) -> Any | None: ...
    def watch(self, wakeup: asyncio.Queue[None]) -> None: ...
    def unwatch(self, wakeup: asyncio.Queue[None]) -> None: ...
    def close(self) -> None: ...


class ReplayPoolPort(Protocol):
    @property
    def stats(self) -> dict[str, int]: ...
    def window(self, *, capacity: int, max_bytes: int) -> ReplayWindowPort: ...
    def close(self) -> None: ...


REPLAY_POOL: ServiceKey[ReplayPoolPort] = ServiceKey("replay_pool")
