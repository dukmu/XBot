"""Typed shared-board service exposed by the team plugin."""
from collections.abc import AsyncIterator, Sequence
from typing import Protocol
from xcore.api.services import ServiceKey


class TeamPort(Protocol):
    enabled: bool
    async def members(self, team: str) -> tuple[str, ...]: ...
    async def count(self, team: str) -> int: ...
    def latest(self, team: str, n: int) -> AsyncIterator[dict]: ...
    def get(self, team: str, ids: Sequence[str]) -> AsyncIterator[tuple[str, dict | None]]: ...
    def after(self, team: str, message_id: str, n: int | None = None) -> AsyncIterator[dict]: ...
    async def add_member(self, team: str, thread: str) -> bool: ...
    async def remove_member(self, team: str, thread: str) -> bool: ...
    async def publish(self, team: str, identity: str, sender: str, content: str, mentions: Sequence[str]) -> dict: ...
    async def retry(self, team: str, message_id: str) -> dict: ...


TEAM: ServiceKey[TeamPort] = ServiceKey("team")
